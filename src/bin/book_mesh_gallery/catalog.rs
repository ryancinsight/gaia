use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use super::model::{GalleryResult, MeshCase};

fn write_section(
    out: &mut String,
    heading: &str,
    image_dir: &str,
    cases: &[MeshCase],
) -> Result<(), std::fmt::Error> {
    writeln!(out, "## {heading}\n")?;
    writeln!(
        out,
        "| Model | Preview | Parameters | Vertices | Faces | Cells | Source |"
    )?;
    writeln!(out, "| --- | --- | --- | ---: | ---: | ---: | --- |")?;
    for case in cases {
        writeln!(
            out,
            "| `{}` | ![{}](figures/models/{}/{}.svg) | {} | {} | {} | {} | `{}` |",
            case.slug,
            case.title,
            image_dir,
            case.slug,
            case.parameters,
            case.mesh.vertex_count(),
            case.mesh.faces.len(),
            case.mesh.cell_count(),
            case.source
        )?;
    }
    writeln!(out)?;
    Ok(())
}

pub(crate) fn write(
    primitive_cases: &[MeshCase],
    channel_cases: &[MeshCase],
    topology_cases: &[MeshCase],
    output: &Path,
) -> GalleryResult<()> {
    let mut markdown = String::with_capacity(64_000);
    markdown.push_str("# Full model catalog\n\n");
    markdown.push_str(
        "This catalog contains an individual rendered panel for every canonical \
Gaia mesh model generated by `book_mesh_gallery`. Panels are deterministic \
orthographic renders from real `IndexedMesh` outputs.\n\n",
    );
    markdown.push_str(
        "For cross-repo visual QA, review these SVGs in Metis viewers and use \
RITK snapshots when a raster triage artifact is required.\n\n",
    );

    write_section(
        &mut markdown,
        "Primitive families",
        "primitive",
        primitive_cases,
    )?;
    write_section(
        &mut markdown,
        "Channel and sweep families",
        "channel",
        channel_cases,
    )?;
    write_section(
        &mut markdown,
        "Topology and volume families",
        "topology",
        topology_cases,
    )?;

    fs::write(output, markdown)?;
    Ok(())
}
