use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use gaia::application::channel::BranchingMeshBuilder;
use gaia::application::watertight::check::check_watertight;
use gaia::domain::core::index::FaceId;
use gaia::domain::geometry::primitives::{Cube, PrimitiveMesh};
use gaia::domain::mesh::IndexedMesh;

use super::model::{GalleryResult, WatertightCase, WatertightRejection};

fn analyzed_case(
    slug: &'static str,
    title: &'static str,
    source: &'static str,
    parameters: &'static str,
    mut mesh: IndexedMesh,
) -> GalleryResult<WatertightCase> {
    mesh.rebuild_edges();
    let Some(edges) = mesh.edges_ref() else {
        return Err(std::io::Error::other("mesh edge store was not built").into());
    };
    let report = check_watertight(&mesh.vertices, &mesh.faces, edges);
    Ok(WatertightCase {
        slug,
        title,
        source,
        parameters,
        mesh,
        report,
    })
}

fn cube() -> GalleryResult<IndexedMesh> {
    Ok(Cube::default().build()?)
}

pub(crate) fn cases() -> GalleryResult<(Vec<WatertightCase>, Vec<WatertightRejection>)> {
    let mut cases = Vec::with_capacity(4);
    cases.push(analyzed_case(
        "closed-cube",
        "Closed cube",
        "src/domain/geometry/primitives/cube.rs",
        "Cube::default(), all six sides present",
        cube()?,
    )?);

    let mut open_cube = cube()?;
    let _ = open_cube.faces.pop();
    cases.push(analyzed_case(
        "removed-face",
        "Removed face",
        "src/application/watertight/check.rs",
        "Closed cube with one triangular face removed",
        open_cube,
    )?);

    let mut non_manifold_cube = cube()?;
    let first_face = *non_manifold_cube.faces.get(FaceId::from_usize(0));
    non_manifold_cube.faces.push(first_face);
    cases.push(analyzed_case(
        "non-manifold-edge",
        "Non-manifold edge",
        "src/application/watertight/check.rs",
        "Closed cube with one face duplicated",
        non_manifold_cube,
    )?);

    let mut reversed_cube = cube()?;
    let Some(first_face) = reversed_cube.faces.iter_mut().next() else {
        return Err(std::io::Error::other("default cube has no faces").into());
    };
    first_face.flip();
    cases.push(analyzed_case(
        "inconsistent-orientation",
        "Inconsistent orientation",
        "src/application/watertight/check.rs",
        "Closed cube with one face winding reversed",
        reversed_cube,
    )?);

    let mut rejections = Vec::with_capacity(2);
    let branching_cases = [
        (
            "branching-bifurcation-rejected",
            "Bifurcation rejected",
            "bifurcation, d=(0.004,0.002), l=(0.020,0.015), angle=0.5, resolution=4",
            BranchingMeshBuilder::bifurcation(0.004, 0.020, 0.002, 0.015, 0.5, 4),
        ),
        (
            "branching-trifurcation-rejected",
            "Trifurcation rejected",
            "trifurcation, d=(0.004,0.002), l=(0.020,0.015), angle=0.5, resolution=6",
            BranchingMeshBuilder::trifurcation(0.004, 0.020, 0.002, 0.015, 0.5, 6),
        ),
    ];
    for (slug, title, parameters, builder) in branching_cases {
        match builder.build_surface() {
            Ok(mesh) => cases.push(analyzed_case(
                slug,
                title,
                "src/application/channel/branching.rs",
                parameters,
                mesh,
            )?),
            Err(error) => rejections.push(WatertightRejection {
                slug,
                title,
                source: "src/application/channel/branching.rs",
                parameters,
                error: error.to_string(),
            }),
        }
    }

    Ok((cases, rejections))
}

pub(crate) fn write_manifest(
    cases: &[WatertightCase],
    rejections: &[WatertightRejection],
    output: &Path,
) -> GalleryResult<()> {
    let mut manifest = String::from(
        "# Watertightness figure manifest\n\nGenerated by `book_mesh_gallery` from Gaia mesh values and the canonical `check_watertight` report. Red and orange diagnostic edges in the figure are derived from the report's edge valence; exact values are listed here.\n\n| Slug | Case | Parameters | Closed | Boundary edges | Non-manifold edges | Orientation | Signed volume | Euler characteristic | Source |\n| --- | --- | --- | --- | ---: | ---: | --- | ---: | ---: | --- |\n",
    );
    for case in cases {
        let report = &case.report;
        let _ = writeln!(
            manifest,
            "| `{}` | {} | {} | {} | {} | {} | {} | {:.6} | {} | `{}` |",
            case.slug,
            case.title,
            case.parameters,
            report.is_closed,
            report.boundary_edge_count,
            report.non_manifold_edge_count,
            report.orientation_consistent,
            report.signed_volume,
            report
                .euler_characteristic
                .map_or_else(|| "n/a".to_owned(), |value| value.to_string()),
            case.source,
        );
    }
    if !rejections.is_empty() {
        manifest.push_str(
            "\n## Rejected branch results\n\nThe branch builder refuses to publish the representative Boolean results. These entries are rendered as rejection panels rather than as geometry.\n\n| Slug | Case | Parameters | Error | Source |\n| --- | --- | --- | --- | --- |\n",
        );
        for rejection in rejections {
            let _ = writeln!(
                manifest,
                "| `{}` | {} | {} | `{}` | `{}` |",
                rejection.slug,
                rejection.title,
                rejection.parameters,
                rejection.error,
                rejection.source,
            );
        }
    }
    fs::write(output, manifest)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn diagnostics_preserve_reported_failure_classes() {
        let (cases, rejections) = cases().expect("diagnostic cases must build");
        let closed = cases
            .iter()
            .find(|case| case.slug == "closed-cube")
            .unwrap();
        assert!(closed.report.is_watertight);
        let open = cases
            .iter()
            .find(|case| case.slug == "removed-face")
            .unwrap();
        assert_eq!(open.report.boundary_edge_count, 3);
        let non_manifold = cases
            .iter()
            .find(|case| case.slug == "non-manifold-edge")
            .unwrap();
        assert_eq!(non_manifold.report.non_manifold_edge_count, 3);
        let reversed = cases
            .iter()
            .find(|case| case.slug == "inconsistent-orientation")
            .unwrap();
        assert!(!reversed.report.orientation_consistent);
        assert_eq!(rejections.len(), 2);
        assert!(rejections[0].error.contains("NotWatertight"));
        assert!(rejections[1].error.contains("NotWatertight"));
    }
}
